import assert from 'node:assert/strict';
import { readFile, mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
const url = process.env.PROTOTYPE_URL || 'http://127.0.0.1:4178/';
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-webgl'] });
await mkdir(new URL('../shots/', import.meta.url), { recursive: true });
let checks = 0;
function ok(condition, message) { assert.ok(condition, message); checks++; console.log('PASS', message); }
async function route(page, hash) { await page.evaluate(hash => { location.hash = hash; }, hash); await page.waitForTimeout(80); }
try {
  for (const [mode, width, height] of [['desktop', 1440, 1000], ['mobile', 390, 844]]) {
    const context = await browser.newContext({ viewport: { width, height }, acceptDownloads: true });
    const page = await context.newPage();
    const errors = [], external = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (/^https?:/.test(request.url()) && !request.url().startsWith(url)) external.push(request.url()); });
    await page.goto(url);
    await page.waitForFunction(() => window.__wearnext?.ready);
    await page.click('[data-action="start-demo"]');
    await page.waitForFunction(() => window.__wearnext.snapshot().mode === 'demo' && document.querySelector('.room-shell'));
    await route(page, 'outfits');
    await page.waitForSelector('.ai-results .outfit-card');
    ok(await page.locator('.ai-results .outfit-card').count() === 6, `${mode}: six prepared AI examples are the first recommendations`);
    ok((await page.locator('details').first().getAttribute('open')) === null, `${mode}: basic rule combinations are secondary`);
    await page.locator('.ai-results [data-action="save-outfit"]').first().click();
    await page.waitForFunction(() => window.__wearnext.snapshot().savedOutfits.length === 1);
    ok((await page.evaluate(() => window.__wearnext.snapshot())).savedOutfits[0].source === 'prepared-ai-sample', `${mode}: saving retains prepared AI provenance`);
    await page.locator('.ai-results [data-action="outfit-detail"]').first().click();
    ok((await page.locator('dialog').innerText()).includes('입어 본 뒤 확인할 점'), `${mode}: sample details explain fit limitations and what to try`);
    await page.click('[data-action="wear"]');
    await page.waitForFunction(() => window.__wearnext.snapshot().decisions.length === 1);
    await page.locator('[data-ai-optional] summary').click();
    await page.fill('#ai-intent', '주말 산책에 편안하고 단정하게');
    const [download] = await Promise.all([page.waitForEvent('download'), page.click('[data-action="ai-download-prompt"]')]);
    const prompt = await readFile(await download.path(), 'utf8');
    ok(prompt.includes('demo-shirt-blue') && prompt.includes('주말 산책') && !prompt.includes('data:image') && !prompt.includes('productURL'), `${mode}: optional AI handoff downloads metadata only`);
    await page.fill('#ai-response', JSON.stringify({ outfits: [{ title: '잘못된 추천', items: ['not-owned', 'demo-chino-beige'], reasons: ['다른 옷'] }], gaps: [] }));
    await page.click('[data-action="ai-import-response"]');
    ok(await page.locator('[data-imported-ai]').count() === 0 && (await page.locator('[data-ai-optional]').innerText()).includes('현재 옷장에 없는'), `${mode}: invented AI clothing is rejected`);
    const candidateId = (await page.evaluate(() => window.__wearnext.snapshot())).products[0].id;
    const result = { purchases: [{ productId: candidateId, itemIds: ['demo-shirt-blue'], decision: 'hold', reasons: ['보유 셔츠와 활용할 상황을 먼저 비교해요.'] }], outfits: [{ title: '차분한 산책 <b>문자</b>', items: ['demo-shirt-blue', 'demo-chino-beige', 'demo-sneaker-white'], reasons: ['밝은 하의와 차분한 셔츠를 연결해요.'] }], gaps: [] };
    await page.fill('#ai-response', JSON.stringify(result));
    await page.click('[data-action="ai-import-response"]');
    await page.waitForSelector('[data-imported-ai] .outfit-card');
    ok((await page.locator('[data-imported-ai]').innerText()).includes('<b>문자</b>') && await page.locator('[data-imported-ai] h3 b').count() === 0, `${mode}: AI output stays text and its source is separate`);
    await page.locator('[data-imported-ai] [data-action="save-outfit"]').click();
    await page.waitForFunction(() => window.__wearnext.snapshot().savedOutfits.length === 2);
    ok((await page.evaluate(() => window.__wearnext.snapshot())).savedOutfits.some(outfit => outfit.source === 'manual-ai'), `${mode}: imported AI outfits save with a valid model schema`);
    await page.reload(); await page.waitForFunction(() => window.__wearnext?.ready);
    await page.waitForSelector('[data-imported-ai] .outfit-card');
    ok((await page.locator('[data-imported-ai]').innerText()).includes('차분한 산책'), `${mode}: imported AI results survive reload without a new request`);
    await route(page, 'discover');
    await page.waitForSelector('[data-ai-purchase]');
    ok((await page.locator('[data-ai-purchase]').innerText()).includes('보류 권장'), `${mode}: purchase reasoning uses the registered candidate`);
    await route(page, 'saved');
    const [cacheDownload] = await Promise.all([page.waitForEvent('download'), page.click('[data-action="export-no-images"]')]);
    const cachedBackup = JSON.parse(await readFile(await cacheDownload.path(), 'utf8'));
    ok(cachedBackup.state.aiRecommendation.result.purchases[0].productId === candidateId, `${mode}: a private backup includes the cached purchase response`);
    await route(page, 'outfits');
    await page.selectOption('#context-form [name="occasion"]', 'weekend');
    await page.click('#context-form [type="submit"]');
    await page.waitForFunction(() => window.__wearnext.snapshot().profile.occasion === 'weekend');
    ok(await page.locator('[data-imported-ai]').count() === 0 && (await page.locator('main').innerText()).includes('이전 AI 응답을 숨겼어요'), `${mode}: changed conditions hide stale AI results with update guidance`);
    ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${mode}: recommendations have no horizontal overflow`);
    await page.screenshot({ path: new URL(`../shots/${mode}-ai-prepared.png`, import.meta.url).pathname, fullPage: true });
    await route(page, 'saved');
    ok((await page.locator('main').innerText()).includes('가져온 AI 응답') && (await page.locator('main').innerText()).includes('미리 준비한 AI 추천'), `${mode}: saved looks preserve both AI sources`);
    await page.click('[data-action="switch-personal"]');
    await page.click('[data-action="confirm-personal"]');
    await page.waitForFunction(() => window.__wearnext.snapshot().mode === 'personal');
    await route(page, 'onboarding');
    const image = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 600; canvas.height = 700; const ctx = canvas.getContext('2d'); ctx.fillStyle = '#fff'; ctx.fillRect(0,0,600,700); ctx.fillStyle = '#556677'; ctx.fillRect(160,130,280,460); return canvas.toDataURL('image/png').split(',')[1]; });
    await page.setInputFiles('#photo-files', { name: 'my-clothes.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') });
    await page.waitForSelector('[data-draft-field="brand"]');
    ok((await page.evaluate(() => window.__wearnext.snapshot())).drafts.every(d => !d.brand && !d.identityConfirmed), `${mode}: a photo does not invent a brand or confirmed identity`);
    const draftId = (await page.evaluate(() => window.__wearnext.snapshot())).drafts[0].id;
    async function fillDraft(field, value) {
      const fieldLocator = page.locator(`[data-draft-field="${field}"]`).first();
      await fieldLocator.fill(value); await fieldLocator.press('Tab');
      await page.waitForFunction(({ id, field, value }) => window.__wearnext.snapshot().drafts.find(d => d.id === id)?.[field] === value, { id: draftId, field, value });
    }
    await page.locator('[data-draft-field="kind"]').first().selectOption('shirt');
    await page.waitForFunction(() => window.__wearnext.snapshot().drafts[0].kind === 'shirt');
    await fillDraft('brand', 'My Own Brand');
    await fillDraft('productName', 'Oxford 2026');
    await fillDraft('styleCode', 'AB-123');
    await fillDraft('productURL', 'https://example.com/my-shirt');
    await page.evaluate(() => { window.__opened = []; window.open = (...args) => { window.__opened.push(args); return null; }; });
    await page.locator('[data-action="identity-search-google"]').first().click();
    const opened = await page.evaluate(() => window.__opened);
    const query = new URL(opened[0][0]).searchParams.get('q');
    ok(query === 'My Own Brand Oxford 2026 AB-123' && !query.includes('my-clothes'), `${mode}: explicit web search sends only entered product text`);
    await page.locator('[data-draft-identity-confirm]').first().check();
    await page.waitForFunction(() => window.__wearnext.snapshot().drafts[0].identityConfirmed);
    ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${mode}: photo identity fields fit the viewport`);
    await page.screenshot({ path: new URL(`../shots/${mode}-identity-review.png`, import.meta.url).pathname, fullPage: true });
    await page.click('[data-action="confirm-drafts"]');
    await page.waitForFunction(() => window.__wearnext.snapshot().items.length > 0);
    let owned = (await page.evaluate(() => window.__wearnext.snapshot())).items[0];
    ok(owned.kind === 'shirt' && owned.category === 'top' && owned.identityConfirmed && owned.productURL === 'https://example.com/my-shirt', `${mode}: confirmed photo identity and corrected type transfer to the owned item`);
    await route(page, 'closet');
    await page.locator('.room-item[data-id]').first().click();
    ok((await page.locator('#room-inspector').innerText()).includes('Oxford 2026'), `${mode}: the room detail exposes saved product identity`);
    await page.click('[data-action="edit-item"]');
    await page.fill('#item-form [name="brand"]', 'A Different Brand');
    ok(!(await page.locator('#item-form [name="identityConfirmed"]').isChecked()), `${mode}: changing identity requires fresh confirmation`);
    await page.selectOption('#item-form [name="kind"]', 'fieldjacket');
    ok(await page.locator('#item-form [name="category"]').inputValue() === 'outer', `${mode}: explicit garment kind updates its category`);
    await page.click('#item-form [type="submit"]');
    await page.waitForFunction(() => !document.querySelector('dialog').open);
    await page.reload(); await page.waitForFunction(() => window.__wearnext?.ready);
    owned = (await page.evaluate(() => window.__wearnext.snapshot())).items[0];
    ok(owned.brand === 'A Different Brand' && !owned.identityConfirmed && owned.kind === 'fieldjacket' && owned.styleCode === 'AB-123' && owned.image, `${mode}: product correction and the original photo persist after reload`);
    await route(page, 'outfits');
    ok(await page.locator('.ai-results .outfit-card').count() === 0 && !(await page.locator('main').innerText()).includes('미리 준비한 AI 추천'), `${mode}: personal wardrobes never claim demo AI possessions`);
    ok(errors.length === 0, `${mode}: no browser execution errors: ${errors.join('; ')}`);
    ok(external.length === 0, `${mode}: no automatic external network requests`);
    await context.close();
  }
  console.log(`${checks} identity and AI browser checks passed.`);
} finally { await browser.close(); }
